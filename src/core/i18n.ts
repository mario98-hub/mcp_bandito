export const STRINGS: Record<Locale, Dict> = { en, it };
export const t = (l: Locale | undefined) => STRINGS[l === 'it' ? 'it' : 'en'];
export type Strings = Dict;

export const MONTH_NAMES: Record<Locale, string[]> = {
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  it: ['Gennaio', 'Febbraio', 'Marzo', 'Aprile', 'Maggio', 'Giugno', 'Luglio', 'Agosto', 'Settembre', 'Ottobre', 'Novembre', 'Dicembre'],
};

export function monthLabel(k: string, l: Locale) {
  const [y, m] = k.split('-').map(Number);
  return `${MONTH_NAMES[l][(m ?? 1) - 1]} ${y}`;
}

export function money(v: number | null | undefined, currency = 'EUR', l: Locale = 'en', sign = false) {
  if (typeof v !== 'number' || !Number.isFinite(v)) return '—';
  const s = new Intl.NumberFormat(l === 'it' ? 'it-IT' : 'en-GB', { style: 'currency', currency, maximumFractionDigits: 0 }).format(Math.round(v));
  return (sign && v > 0.5 ? '+' : '') + s.replace('-', '−');
}
export function pct(v: number | null | undefined, l: Locale = 'en', d = 0) {
  if (typeof v !== 'number' || !Number.isFinite(v)) return '—';
  return new Intl.NumberFormat(l === 'it' ? 'it-IT' : 'en-GB', { style: 'percent', maximumFractionDigits: d, minimumFractionDigits: d }).format(v).replace('-', '−');
}
export function num(v: number | null | undefined, l: Locale = 'en', d = 1) {
  if (typeof v !== 'number' || !Number.isFinite(v)) return '—';
  return new Intl.NumberFormat(l === 'it' ? 'it-IT' : 'en-GB', { maximumFractionDigits: d }).format(v);
}
